#[derive(Table, Debug, Clone, PartialEq)]
#[besu(table = "native_posts")]
pub struct Post {
    #[besu(primary_key, auto_increment)]
    pub id: i64,
    pub title: String,
    #[besu(references = "native_users.id", on_delete = "cascade")]
    pub author_id: i64,
}

#[tokio::test]
async fn ddl_insert_select_returning_joins_and_nulls() {
    let db = database().await;

    let created = db
        .push([native_users.def(), native_posts.def()])
        .await
        .unwrap();
    assert!(
        created
            .statements
            .iter()
            .any(|statement| statement.contains("GENERATED BY DEFAULT AS IDENTITY")),
        "the identity column must be declared: {:?}",
        created.statements
    );

    let alice = db
        .insert(native_users)
        .value(native_users.insert("a@example.com", "Alice", 30))
        .returning(native_users)
        .await
        .unwrap()
        .remove(0);
    assert_eq!(alice.id, 1);
    assert_eq!(alice.bio, None, "an omitted nullable column is NULL");

    db.insert(native_users)
        .value(native_users.insert("b@example.com", "Bob", 25).bio("Rust"))
        .await
        .unwrap();
    db.insert(native_posts)
        .value(native_posts.insert("Hello", alice.id))
        .await
        .unwrap();

    // A filter on text, a filter on an integer and a join that reads columns from both
    // sides, so the entire prepared-statement path is exercised.
    let adults: Vec<User> = db
        .select(native_users)
        .filter(native_users.age.gte(26))
        .order_by(native_users.id.asc())
        .await
        .unwrap();
    assert_eq!(adults.len(), 1);
    assert_eq!(adults[0].name, "Alice");

    let found: Vec<(String, String)> = db
        .select(native_posts)
        .inner_join(native_users, eq(native_users.id, native_posts.author_id))
        .pick((native_posts.title, native_users.name))
        .filter(native_users.email.eq("a@example.com"))
        .await
        .unwrap();
    assert_eq!(found, [("Hello".to_owned(), "Alice".to_owned())]);

    // A null comparison and a null read through an outer join.
    let no_bio: Vec<User> = db
        .select(native_users)
        .filter(native_users.bio.is_null())
        .await
        .unwrap();
    assert_eq!(no_bio.len(), 1);

    let rows: Vec<(String, Option<String>)> = db
        .select(native_users)
        .left_join(native_posts, eq(native_posts.author_id, native_users.id))
        .pick((native_users.name, native_posts.title))
        .order_by(native_users.id.asc())
        .await
        .unwrap();
    assert_eq!(
        rows,
        [
            ("Alice".to_owned(), Some("Hello".to_owned())),
            ("Bob".to_owned(), None),
        ]
    );
}

