//! The native `tokio-postgres` driver, end to end.
//!
//! Everything here runs against the PostgreSQL server the rest of the suite uses. The
//! shared lock makes the binaries take turns; the native tests only add the driver surface
//! that the sqlx suite cannot exercise: real streaming from a pool, transactions that own
//! their connection, and the binary type mapping against the server's inferred types.
#![cfg(feature = "native")]
#![allow(
    missing_docs,
    clippy::unwrap_used,
    clippy::panic,
    clippy::too_many_arguments
)]

mod common;

use besu::prelude::*;
use besu::schema::{Migrator, Schema};
use besu::{BitString, Bound, Cidr, Driver, Inet, Range, Sql, SqlInterval};
use besu_postgres::{Native, NativeDatabase, NativeError};

/// A database for one test, keeping the suite lock's connection alive beside it.
struct TestDatabase {
    db: NativeDatabase,
    _lock: NativeDatabase,
}

impl core::ops::Deref for TestDatabase {
    type Target = NativeDatabase;

    fn deref(&self) -> &NativeDatabase {
        &self.db
    }
}

async fn database() -> TestDatabase {
    let (db, lock) = common::native_database().await;
    common::reset(&db).await;
    TestDatabase { db, _lock: lock }
}

