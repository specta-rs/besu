#[derive(Table, Debug, Clone, PartialEq)]
#[besu(table = "native_spatial")]
pub struct Spatial {
    #[besu(primary_key)]
    pub id: i64,
    pub any: besu::Geometry,
    #[besu(sql_type = "besu::Point<4326>")]
    pub point: besu::Geometry,
    #[besu(sql_type = "besu::VectorOf<3>")]
    pub xyz: besu::Vector,
}

async fn extension(db: &NativeDatabase, name: &str) -> bool {
    let statement = format!("CREATE EXTENSION IF NOT EXISTS {name}");
    match db.execute(besu::Fragment::new(statement)).await {
        Ok(_) => true,
        Err(_) => {
            eprintln!("skipping: the server does not have the `{name}` extension");
            false
        }
    }
}

#[tokio::test]
async fn postgis_and_pgvector_round_trip_when_installed() {
    let db = database().await;
    if !extension(&db, "postgis").await || !extension(&db, "vector").await {
        return;
    }

    db.push([native_spatial.def()]).await.unwrap();
    let point =
        besu::Geometry::from_hex("0101000020E6100000000000000000F03F0000000000000040").unwrap();
    let expected = Spatial {
        id: 1,
        any: point.clone(),
        point: point.clone(),
        xyz: besu::Vector::new(vec![1.0, 2.5, -3.0]),
    };
    db.insert(native_spatial)
        .value(native_spatial.insert(
            expected.id,
            expected.any.clone(),
            expected.point.clone(),
            expected.xyz.clone(),
        ))
        .await
        .unwrap();

    let stored: Vec<Spatial> = db.select(native_spatial).await.unwrap();
    assert_eq!(stored, [expected]);
    assert_eq!(stored[0].point.srid(), Some(4326));
}

