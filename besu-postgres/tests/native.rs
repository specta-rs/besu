#[tokio::test]
async fn a_value_that_does_not_match_its_rust_type_is_an_error() {
    let db = database().await;

    let error = db
        .execute(sql!("SELECT 'not a number'::text"))
        .all::<i32>()
        .await
        .unwrap_err();
    assert!(
        matches!(
            error,
            NativeError::Core(besu::Error::Decode { column: 0, .. })
        ),
        "unexpected error: {error}"
    );

    let mut statement = Sql::<besu_postgres::Postgres>::raw("SELECT $1::jsonb");
    statement.push_arg(Value::Json(br#"{"a":"#.to_vec()));
    let error = db.driver().query(&statement).await.unwrap_err();
    assert!(
        error.to_string().contains("cannot encode value `json`"),
        "unexpected error: {error}"
    );
}

/// A domain is a named type whose values are the base type's values. The column keeps the
/// domain's name, and the value is written and read through the base type's encoding.
#[tokio::test]
async fn a_domain_is_written_and_read_through_its_base_type() {
    let db = database().await;
    db.execute(besu::Fragment::new(
        "CREATE DOMAIN native_positive AS integer CHECK (VALUE > 0)".to_owned(),
    ))
    .await
    .unwrap();
    db.execute(besu::Fragment::new(
        "CREATE TABLE native_domain_holder (value native_positive NOT NULL, label text NOT NULL)"
            .to_owned(),
    ))
    .await
    .unwrap();

    let introspected = db.introspect().await.unwrap();
    let table = introspected.table("native_domain_holder").unwrap();
    assert_eq!(
        table.column("value").unwrap().ty,
        TypeDef::Domain(besu::DomainDef::new("native_positive", &TypeDef::Int4))
    );
    assert!(db.push_schema(&introspected).await.unwrap().is_empty());

    // The server infers the domain type for the placeholder; the encoder resolves it to
    // `INTEGER` before writing four bytes.
    db.execute(sql!(
        "INSERT INTO native_domain_holder (value, label) VALUES (?, ?)",
        7_i32,
        "seven"
    ))
    .await
    .unwrap();

    let value: i32 = db
        .execute(sql!("SELECT value FROM native_domain_holder"))
        .all::<i32>()
        .await
        .unwrap()
        .remove(0);
    assert_eq!(value, 7);
    let label: String = db
        .execute(sql!("SELECT label FROM native_domain_holder"))
        .all::<String>()
        .await
        .unwrap()
        .remove(0);
    assert_eq!(label, "seven");
    // A non-numeric domain value does not pretend to be a number.
    assert!(
        db.execute(sql!("SELECT label FROM native_domain_holder"))
            .all::<i32>()
            .await
            .is_err()
    );
}
