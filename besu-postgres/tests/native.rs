#[tokio::test]
async fn push_creates_and_alters_a_table() {
    let db = database().await;

    let created = db.push([account_v1::native_accounts.def()]).await.unwrap();
    assert!(
        created
            .statements
            .iter()
            .any(|statement| statement.starts_with("CREATE TABLE")),
        "got {:?}",
        created.statements
    );
    db.insert(account_v1::native_accounts)
        .value(account_v1::native_accounts.insert(1, "Oscar"))
        .await
        .unwrap();

    let altered = db.push([account_v2::native_accounts.def()]).await.unwrap();
    assert!(
        altered
            .statements
            .iter()
            .any(|statement| statement.contains("ADD COLUMN")),
        "got {:?}",
        altered.statements
    );
    assert!(
        db.push([account_v2::native_accounts.def()])
            .await
            .unwrap()
            .is_empty()
    );

    // The existing row survived, with the new column NULL.
    let rows: Vec<account_v2::AccountV2> = db.select(account_v2::native_accounts).await.unwrap();
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0].name, "Oscar");
    assert_eq!(rows[0].email, None);
}

#[tokio::test]
async fn push_creates_enums_domains_sequences_and_views() {
    let db = database().await;

    // An enum declared from Rust.
    db.push([native_reviews.def()]).await.unwrap();
    let snapshot = db.introspect().await.unwrap();
    assert_eq!(snapshot.enums.len(), 1);
    assert_eq!(snapshot.enums[0].name, "mood");

    // A domain, a standalone sequence and a view are IR objects a snapshot can carry, so
    // pushing one creates it and introspection reports it back.
    let mut desired = Schema::from_defs(&[native_reviews.def()]);
    desired.domains.push(besu::schema::Domain {
        name: "native_price".into(),
        base: TypeDef::Decimal(10, 2),
    });
    desired.sequences.push(besu::schema::Sequence {
        name: "native_ticket".into(),
        schema: None,
        data_type: "bigint".into(),
        start: 1,
        increment: 1,
        min: None,
        max: None,
        cycle: false,
        cache: 1,
    });
    desired.views.push(besu::schema::View {
        name: "native_prices".into(),
        definition: "SELECT 1 AS amount".into(),
        materialised: false,
    });
    db.push_schema(&desired).await.unwrap();

    let stored = db.introspect().await.unwrap();
    assert!(stored.find_domain("native_price").is_some());
    assert!(stored.find_sequence(None, "native_ticket").is_some());
    assert!(stored.views.iter().any(|view| view.name == "native_prices"));
    assert!(db.push_schema(&stored).await.unwrap().is_empty());
}

#[tokio::test]
async fn migrate_from_a_directory() {
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(
        dir.path().join("0001_create_people.sql"),
        "CREATE TABLE native_people (id BIGINT PRIMARY KEY, name TEXT NOT NULL);",
    )
    .unwrap();
    std::fs::write(
        dir.path().join("0002_add_email.sql"),
        "ALTER TABLE native_people ADD COLUMN email TEXT;\n\
         CREATE UNIQUE INDEX native_people_email_idx ON native_people (email);",
    )
    .unwrap();

    let migrator = Migrator::from_dir(dir.path()).unwrap();
    let db = database().await;

    let applied = db.migrate(&migrator).await.unwrap();
    assert_eq!(
        applied.iter().map(|m| m.version).collect::<Vec<_>>(),
        [1, 2]
    );

    // The journal remembers what ran, and it is not part of the introspected schema.
    assert!(db.migrate(&migrator).await.unwrap().is_empty());
    assert!(
        db.introspect()
            .await
            .unwrap()
            .table("_besu_migrations")
            .is_none()
    );

    db.execute(sql!(
        "INSERT INTO native_people (id, name, email) VALUES (?, ?, ?)",
        1_i64,
        "Oscar",
        "o@example.com"
    ))
    .await
    .unwrap();
    let rows = db
        .execute(sql!(
            "SELECT name FROM native_people WHERE email = ?",
            "o@example.com"
        ))
        .all::<(String,)>()
        .await
        .unwrap();
    assert_eq!(rows, [("Oscar".to_owned(),)]);
}

