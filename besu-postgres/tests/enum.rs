//! A PostgreSQL enum declared from Rust: the labels become a named type, the column names
//! it, introspection reports it as a `Custom` type, and a changed label set is an
//! `ALTER TYPE ... ADD VALUE`.
#![cfg(feature = "sqlx")]
#![allow(missing_docs, clippy::unwrap_used, clippy::panic)]

mod common;

use besu::TypeDef;
use besu::prelude::*;
use besu::schema::{Change, Enum, Schema};

#[derive(Clone, Copy, Debug, PartialEq, Eq, besu::SqlEnum)]
#[besu(rename_all = "snake_case")]
pub enum Mood {
    Happy,
    #[besu(rename = "meh")]
    Neutral,
    Sad,
}

#[derive(Table, Debug, Clone, PartialEq)]
#[besu(table = "reviews")]
pub struct Review {
    #[besu(primary_key, auto_increment)]
    pub id: i64,
    #[besu(sql_type = "Mood")]
    pub mood: Mood,
}

#[tokio::test]
async fn a_declared_enum_creates_its_type_and_round_trips() {
    let db = common::database().await;
    common::reset(&db).await;

    let first = db.push([reviews.def()]).await.unwrap();
    assert_eq!(
        first.statements,
        [
            r#"CREATE TYPE "mood" AS ENUM ('happy', 'meh', 'sad')"#,
            r#"CREATE TABLE "reviews" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "mood" "mood" NOT NULL)"#,
        ]
    );
    assert!(
        matches!(&first.changes[0], Change::CreateEnum(e) if e.name == "mood"),
        "the type must be created before the table: {:?}",
        first.changes
    );

    let created = db
        .insert(reviews)
        .value(reviews.insert(Mood::Neutral))
        .returning(reviews)
        .await
        .unwrap();
    assert_eq!(created.len(), 1);
    assert_eq!(created[0].mood, Mood::Neutral);

    // A comparison against a variant binds the same untyped label, which the server resolves
    // against the enum type of the column.
    let found: Vec<Review> = db
        .select(reviews)
        .filter(reviews.mood.eq(Mood::Neutral))
        .await
        .unwrap();
    assert_eq!(found.len(), 1);
    assert!(
        db.select(reviews)
            .filter(reviews.mood.eq(Mood::Sad))
            .await
            .unwrap()
            .is_empty()
    );

    // The type lives beside the table, and the column names it as a `Custom` type.
    let introspected = db.introspect().await.unwrap();
    assert_eq!(
        introspected.enums,
        [Enum {
            name: "mood".into(),
            values: vec!["happy".into(), "meh".into(), "sad".into()],
        }]
    );
    assert_eq!(
        introspected
            .table("reviews")
            .unwrap()
            .column("mood")
            .unwrap()
            .ty,
        TypeDef::Custom("mood".into())
    );

    // The declaration and the server agree, so the second push is a no-op.
    let second = db.push([reviews.def()]).await.unwrap();
    assert!(second.is_empty(), "got {:?}", second.changes);
}

#[tokio::test]
async fn a_new_label_is_an_alter_type_not_a_table_rewrite() {
    let db = common::database().await;
    common::reset(&db).await;
    db.push([reviews.def()]).await.unwrap();

    // A declared schema says the type has one more label. The only change is the append,
    // which PostgreSQL spells `ALTER TYPE ... ADD VALUE`.
    let mut grown = Schema::from_defs(&[reviews.def()]);
    grown.enums[0].values.push("ecstatic".into());

    let applied = db.push_schema(&grown).await.unwrap();
    assert_eq!(
        applied.changes,
        [Change::AddEnumValue {
            name: "mood".into(),
            value: "ecstatic".into(),
        }]
    );
    assert_eq!(
        applied.statements,
        [r#"ALTER TYPE "mood" ADD VALUE 'ecstatic'"#]
    );

    // The extra value is now usable and reads back as its label.
    let created = db
        .insert(reviews)
        .value(reviews.insert(Mood::Sad))
        .returning(reviews)
        .await
        .unwrap();
    assert_eq!(created[0].mood, Mood::Sad);

    let introspected = db.introspect().await.unwrap();
    assert_eq!(
        introspected.find_enum("mood").unwrap().values,
        ["happy", "meh", "sad", "ecstatic"]
    );
}
