//! Column types, and typed references to a table's columns.

use core::marker::PhantomData;

use alloc::string::String;

use besu_core::value::Value;
use besu_core::TypeDef;


/// A SQL column type, expressed as a Rust type.
///
/// Implementations exist for every built-in type. You normally never name these directly:
/// the [`#[derive(Table)]`](https://docs.rs/besu/latest/besu/derive.Table.html) macro maps
/// Rust field types onto the matching [`SqlType`].
pub trait SqlType: 'static {
    /// The canonical type description.
    const DEF: TypeDef;

    /// The Rust value this column holds.
    ///
    /// It must be convertible into a bound SQL value, which is what lets a column be used
    /// everywhere an expression is expected.
    type Rust: 'static + Into<Value>;
}

/// Marks a column as `NOT NULL`.
pub struct NonNull;

/// Marks a column as nullable, so its Rust type is `Option<T>`.
pub struct Nullable;

/// How a column's Rust type accounts for SQL `NULL`.
///
/// This exists as its own parameter rather than by wrapping the [`SqlType`] so that
/// `Option<T>` never nests: `Nullable` composed with a nullable type would otherwise be a
/// type-level footgun.
pub trait Nullability: 'static {
    /// The Rust type of the column, given the type of its non-null value.
    type Wrap<T>;

    /// Whether `NULL` is allowed.
    const NULLABLE: bool;
}

impl Nullability for NonNull {
    type Wrap<T> = T;
    const NULLABLE: bool = false;
}

impl Nullability for Nullable {
    type Wrap<T> = Option<T>;
    const NULLABLE: bool = true;
}

/// A typed reference to a single database column.
///
/// Columns are zero-sized: the table name comes from `T`'s [`TableDef`](crate::TableDef)
/// and the column name is stored inline as a `&'static str`. Copying one is free, which is
/// why `users.id` can be used as many times as you like without any ceremony.
///
/// ```ignore
/// #[derive(Table)]
/// pub struct User {
///     pub id: i64,
///     pub name: String,
/// }
///
/// // `user` is a zero-sized table handle generated by the derive.
/// db.select(user).filter(eq(user.id, 1))
/// ```
pub struct Column<T, S: SqlType, N: Nullability = NonNull> {
    name: &'static str,
    phantom: PhantomData<fn() -> (T, S, N)>,
}

impl<T, S: SqlType, N: Nullability> Column<T, S, N> {
    /// Construct a column reference. Only the derive macro is expected to call this.
    pub const fn new(name: &'static str) -> Self {
        Self {
            name,
            phantom: PhantomData,
        }
    }

    /// The column name exactly as it appears in SQL.
    pub const fn name(&self) -> &'static str {
        self.name
    }

    /// The canonical SQL type.
    pub const fn type_def(&self) -> TypeDef {
        S::DEF
    }

    /// Whether the column is nullable.
    pub const fn nullable(&self) -> bool {
        N::NULLABLE
    }
}

impl<T, S: SqlType, N: Nullability> Clone for Column<T, S, N> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<T, S: SqlType, N: Nullability> Copy for Column<T, S, N> {}

impl<T, S: SqlType, N: Nullability> core::fmt::Debug for Column<T, S, N> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_tuple("Column").field(&self.name).finish()
    }
}

impl<T, S: SqlType, N: Nullability> PartialEq for Column<T, S, N> {
    fn eq(&self, other: &Self) -> bool {
        self.name == other.name
    }
}

impl<T, S: SqlType, N: Nullability> Eq for Column<T, S, N> {}

macro_rules! sql_types {
    ($($(#[$attr:meta])* $name:ident = $def:expr => $rust:ty),* $(,)?) => {
        $(
            $(#[$attr])*
            #[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
            #[allow(non_camel_case_types)]
            pub struct $name;

            impl SqlType for $name {
                const DEF: TypeDef = $def;
                type Rust = $rust;
            }
        )*
    };
}

sql_types! {
    /// SQL `BOOLEAN`.
    Bool = TypeDef::Bool => bool,
    /// SQL 16-bit integer.
    Int2 = TypeDef::Int2 => i16,
    /// SQL 32-bit integer.
    Int4 = TypeDef::Int4 => i32,
    /// SQL 64-bit integer.
    Int8 = TypeDef::Int8 => i64,
    /// SQL 8-bit integer, widened into a 16-bit column because no database has an `i8`.
    Int1 = TypeDef::Int2 => i8,
    /// SQL 32-bit float.
    Float4 = TypeDef::Float4 => f32,
    /// SQL 64-bit float.
    Float8 = TypeDef::Float8 => f64,
    /// SQL `TEXT`.
    Text = TypeDef::Text => String,
    /// SQL `BYTEA` / `BLOB`.
    Bytes = TypeDef::Bytes => alloc::vec::Vec<u8>,
    /// SQL date with no time.
    Date = TypeDef::Date => chrono::NaiveDate,
    /// SQL time with no date.
    Time = TypeDef::Time => chrono::NaiveTime,
    /// SQL timestamp with no timezone.
    Timestamp = TypeDef::Timestamp => chrono::NaiveDateTime,
    /// SQL timestamp with timezone.
    TimestampTz = TypeDef::TimestampTz => chrono::DateTime<chrono::Utc>,
    /// SQL `UUID`.
    Uuid = TypeDef::Uuid => uuid::Uuid,
    /// SQL `JSON`.
    Json = TypeDef::Json => serde_json::Value,
    /// SQL `JSONB`.
    Jsonb = TypeDef::Jsonb => serde_json::Value,
}

/// SQL unsigned 8-bit integer, widened into a 16-bit column.
