#[command(about = "Generate the Rust code, instead of using the besu::Table macro.")]
pub struct Command {}

const HEADER: &str = "// This file has been generated by Besu. DO NOT EDIT.
";

impl Command {
    pub fn run(&self) {
        // TODO: Load from somewhere
        let models = vec![Model {
            name: "User".into(),
            fields: vec![ModelField {
                name: "id".into(),
                ty: ModelFieldType::String,
            }],
        }];

        let types = models.into_iter().map(|m| {
            quote! {}
        });

        let result = quote! {
            #(#types)*
        };

        // TODO: Figure out path properly
        std::fs::write("./schema.rs", format!("{HEADER}{}", result.to_string())).unwrap();
        info!("Generated");
    }
}

