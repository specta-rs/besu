use std::path::PathBuf;

/// Turn the difference between a snapshot and the database into migration files.
#[derive(clap::Args)]
pub struct Args {
    /// The database to diff against, for example `postgres://user:pass@host/db`.
    #[arg(long, env = "DATABASE_URL")]
    pub database: String,
    /// The schema snapshot that describes the desired state.
    #[arg(long)]
    pub schema: PathBuf,
    /// The directory to write migration files into.
    #[arg(long, default_value = "migrations")]
    pub out: PathBuf,
    /// The name to give the generated migration.
    #[arg(long, default_value = "schema")]
    pub name: String,
}

pub async fn run(args: Args) -> anyhow::Result<()> {
    let desired = besu::schema::Schema::load(&args.schema)?;
    let db = super::database::AnyDatabase::connect(&args.database).await?;
    let current = db.introspect().await?;

    let changes = db.diff(&current, &desired);
    if changes.is_empty() {
        println!("schema is up to date; nothing to generate");
        return Ok(());
    }

    let statements = match &db {
        super::database::AnyDatabase::Sqlite(_) => {
            besu::schema::ddl::Ddl::apply(&besu_sqlite::SQLiteDdl, &changes)
        }
        super::database::AnyDatabase::Postgres(_) => {
            besu::schema::ddl::Ddl::apply(&besu_postgres::PostgresDdl, &changes)
        }
        super::database::AnyDatabase::MySql(_) => {
            besu::schema::ddl::Ddl::apply(&besu_mysql::MySqlDdl, &changes)
        }
    };

    std::fs::create_dir_all(&args.out)?;
    let version = next_version(&args.out)?;
    let name = args.name.replace(' ', "_").to_ascii_lowercase();
    let path = args.out.join(format!("{version:04}_{name}.sql"));

    let can_alter = match &db {
        super::database::AnyDatabase::Sqlite(_) => {
            besu::schema::Ddl::can_alter_column(&besu_sqlite::SQLiteDdl)
        }
        super::database::AnyDatabase::Postgres(_) => {
            besu::schema::Ddl::can_alter_column(&besu_postgres::PostgresDdl)
        }
        super::database::AnyDatabase::MySql(_) => {
            besu::schema::Ddl::can_alter_column(&besu_mysql::MySqlDdl)
        }
    };

    let mut sql = String::new();
    sql.push_str("-- Generated by `besu generate`.\n");
    sql.push_str("-- Review before applying: dropping a column loses its data.\n");
    if !can_alter
        && changes
            .iter()
            .any(|change| matches!(change, besu::schema::Change::AlterColumn { .. }))
    {
        sql.push_str(
            "--\n-- WARNING: this database cannot change a column in place, so each altered\n\
             -- column below is dropped and recreated. Any data in it will be lost unless you\n\
             -- copy it across yourself before running this file.\n",
        );
    }
    sql.push('\n');
    for statement in &statements {
        sql.push_str(statement);
        sql.push_str(";\n");
    }
    std::fs::write(&path, sql)?;

    println!(
        "wrote {} statement(s) to {}",
        statements.len(),
        path.display()
    );
    Ok(())
}

fn next_version(dir: &std::path::Path) -> anyhow::Result<i64> {
    let mut highest = 0;
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let name = entry.file_name();
        let Some(name) = name.to_str() else { continue };
        let Some((version, _)) = name.split_once('_') else {
            continue;
        };
        if let Ok(version) = version.parse::<i64>() {
            highest = highest.max(version);
        }
    }
    Ok(highest + 1)
}
