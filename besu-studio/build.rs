//! Embed the built studio frontend into the crate.
//!
//! `web/dist` is built by Vite (`pnpm --dir web build`) and committed, so a
//! checkout builds with Cargo alone and the published crate still serves a
//! working UI. This script turns the directory into a sorted table of
//! `(path, bytes, content type)` and writes it to `OUT_DIR`, which
//! `src/assets.rs` includes.

use std::collections::BTreeMap;
use std::path::Path;

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    let dist = Path::new(&manifest).join("web/dist");

    println!("cargo:rerun-if-changed=web/dist");
    println!("cargo:rerun-if-changed=build.rs");

    let mut files: BTreeMap<String, &'static str> = BTreeMap::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut files);
    }

    // A checkout without a built bundle still compiles; the studio then explains
    // how to build one instead of serving a blank page.
    if !files.contains_key("index.html") {
        let placeholder = Path::new(&out).join("placeholder.html");
        std::fs::write(&placeholder, PLACEHOLDER).expect("write placeholder");
        files.insert(
            "index.html".to_owned(),
            "concat!(env!(\"OUT_DIR\"), \"/placeholder.html\")",
        );
    }

    let mut source = String::from(
        "// @generated by build.rs: the studio frontend, embedded as bytes.\n\
         pub(crate) static ASSETS: &[(&str, &[u8], &str)] = &[\n",
    );

    for (path, include) in &files {
        let bytes = if include.starts_with("concat!") {
            include.to_string()
        } else {
            format!("concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/web/dist/{path}\")")
        };
        source.push_str(&format!(
            "    ({path:?}, include_bytes!({bytes}), {:?}),\n",
            content_type(path)
        ));
    }

    source.push_str("];\n");

    std::fs::write(Path::new(&out).join("assets.rs"), source).expect("write assets.rs");
}

fn collect(root: &Path, dir: &Path, files: &mut BTreeMap<String, &'static str>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };

    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, files);
            continue;
        }

        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        let key = relative.to_string_lossy().replace('\\', "/");
        if path.is_file() {
            files.insert(key, "");
        }
    }
}

/// The content type a browser needs for one asset.
fn content_type(path: &str) -> &'static str {
    match path.rsplit_once('.').map(|(_, extension)| extension) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("webp") => "image/webp",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("woff") => "font/woff",
        Some("txt") => "text/plain; charset=utf-8",
        Some("map") => "application/json",
        _ => "application/octet-stream",
    }
}

const PLACEHOLDER: &str = r#"<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><title>besu studio</title></head>
<body style="font:14px/1.6 system-ui;margin:3rem auto;max-width:34rem;padding:0 1.5rem">
<h1 style="font-size:1.1rem">besu studio</h1>
<p>The frontend has not been built. Run
<code>pnpm --dir besu-studio/web install &amp;&amp; pnpm --dir besu-studio/web build</code>
and rebuild this crate.</p>
</body>
</html>
"#;
