import { displayType, typeArg, typeName } from "../../lib/format";
import type { Column, Table } from "../../lib/types";

/**
 * Render the IR as the DDL a user would have written. This is a preview, not a
 * migration: it reads the introspected table and spells it in the connection's
 * dialect so it can be copied into an editor or a review.
 */

const isMySql = (dialect: string | undefined): boolean => dialect === "mysql";

/** An identifier in the connection's quoting style. */
export function quoteIdent(name: string, dialect: string | undefined): string {
  if (isMySql(dialect)) return `\`${name.replaceAll("`", "``")}\``;
  return `"${name.replaceAll('"', '""')}"`;
}

/** `"app"."users"` when the table carries a schema, otherwise just the name. */
export function qualifiedName(table: Table, dialect: string | undefined): string {
  const name = quoteIdent(table.name, dialect);
  return table.schema ? `${quoteIdent(table.schema, dialect)}.${name}` : name;
}

/**
 * The column's type in the dialect's spelling. The studio's canonical names
 * (`int8`, `bool`) are valid in SQLite and PostgreSQL; MySQL needs its own.
 */
function columnType(column: Column, dialect: string | undefined): string {
  const shown = displayType(column.ty);
  if (!isMySql(dialect)) return shown;

  const arg = typeArg(column.ty);
  switch (typeName(column.ty)) {
    case "Bool":
      return "tinyint(1)";
    case "Int2":
      return "smallint";
    case "Int4":
      return "int";
    case "Int8":
      return "bigint";
    case "UInt":
      return "int unsigned";
    case "Float4":
      return "float";
    case "Float8":
      return "double";
    case "Text":
      return "text";
    case "Json":
    case "Jsonb":
      return "json";
    case "Uuid":
      return "char(36)";
    case "Date":
      return "date";
    case "Time":
    case "TimeTz":
      return "time";
    case "Timestamp":
    case "TimestampTz":
      return "datetime";
    case "Char":
      return `char(${String(arg ?? 1)})`;
    case "VarChar":
      return `varchar(${String(arg ?? 255)})`;
    default:
      return shown;
  }
}

const ACTIONS: Record<string, string> = {
  cascade: "CASCADE",
  restrict: "RESTRICT",
  noaction: "NO ACTION",
  setnull: "SET NULL",
  setdefault: "SET DEFAULT",
};

/** `Cascade` -> `CASCADE`, `SetNull` -> `SET NULL`, `Default` -> nothing. */
function referentialAction(value: string | undefined): string | null {
  if (!value || value.toLowerCase() === "default") return null;
  const key = value.replace(/[^a-z]/gi, "").toLowerCase();
  if (ACTIONS[key]) return ACTIONS[key];
  return value.replace(/([a-z])([A-Z])/g, "$1 $2").toUpperCase();
}

function columnSql(
  column: Column,
  table: Table,
  dialect: string | undefined,
  inlineUnique: boolean,
): string {
  const parts = [quoteIdent(column.name, dialect), columnType(column, dialect)];

  if (column.auto_increment) {
    parts.push(isMySql(dialect) ? "AUTO_INCREMENT" : "GENERATED BY DEFAULT AS IDENTITY");
  }
  if (column.generated) {
    const mode = column.generated.stored === false ? "VIRTUAL" : "STORED";
    parts.push(`GENERATED ALWAYS AS (${column.generated.expression}) ${mode}`);
  }
  if (!column.nullable) parts.push("NOT NULL");
  if (column.default !== undefined) parts.push(`DEFAULT ${column.default}`);
  if (inlineUnique) parts.push("UNIQUE");

  // A single-column key reads better inline; composites are table constraints.
  const singleKey =
    column.primary_key && table.columns.filter((other) => other.primary_key).length === 1;
  if (singleKey) parts.push("PRIMARY KEY");

  return parts.join(" ");
}

/** The whole table as one `CREATE TABLE` plus any separate index statements. */
export function createTableSql(table: Table, dialect: string | undefined): string {
  const uniques = table.uniques ?? [];
  const uniqueSets = new Set(uniques.map((unique) => unique.columns.join("\u0000")));
  const key = table.columns.filter((column) => column.primary_key);

  const columns = table.columns.map((column) =>
    columnSql(
      column,
      table,
      dialect,
      Boolean(column.unique) && !column.primary_key && !uniqueSets.has(column.name),
    ),
  );

  const constraints: string[] = [];

  if (key.length > 1) {
    constraints.push(`PRIMARY KEY (${key.map((c) => quoteIdent(c.name, dialect)).join(", ")})`);
  }

  for (const unique of uniques) {
    const columnList = unique.columns.map((name) => quoteIdent(name, dialect)).join(", ");
    constraints.push(`CONSTRAINT ${quoteIdent(unique.name, dialect)} UNIQUE (${columnList})`);
  }

  for (const foreign of table.foreign_keys ?? []) {
    const columnList = foreign.columns.map((name) => quoteIdent(name, dialect)).join(", ");
    const target = foreign.references_columns
      .map((name) => quoteIdent(name, dialect))
      .join(", ");
    let clause = `CONSTRAINT ${quoteIdent(foreign.name, dialect)} FOREIGN KEY (${columnList}) REFERENCES ${quoteIdent(foreign.references_table, dialect)} (${target})`;
    const onDelete = referentialAction(foreign.on_delete);
    const onUpdate = referentialAction(foreign.on_update);
    if (onDelete) clause += ` ON DELETE ${onDelete}`;
    if (onUpdate) clause += ` ON UPDATE ${onUpdate}`;
    constraints.push(clause);
  }

  for (const check of table.checks ?? []) {
    constraints.push(
      `CONSTRAINT ${quoteIdent(check.name, dialect)} CHECK (${check.expression})`,
    );
  }

  const lines = [...columns, ...constraints];
  const body =
    lines.length === 0
      ? `CREATE TABLE ${qualifiedName(table, dialect)} ();`
      : `CREATE TABLE ${qualifiedName(table, dialect)} (\n${lines
          .map((line) => `  ${line}`)
          .join(",\n")}\n);`;

  const indexes = (table.indexes ?? []).map((index) => {
    const columnList = index.columns.map((name) => quoteIdent(name, dialect)).join(", ");
    const unique = index.unique ? "UNIQUE " : "";
    // MySQL has no partial indexes, so a predicate is Postgres/SQLite only.
    const predicate =
      index.predicate && !isMySql(dialect) ? ` WHERE ${index.predicate}` : "";
    return `CREATE ${unique}INDEX ${quoteIdent(index.name, dialect)} ON ${qualifiedName(table, dialect)} (${columnList})${predicate};`;
  });

  return [body, ...indexes].join("\n\n");
}
